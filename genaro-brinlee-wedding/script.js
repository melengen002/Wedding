// Countdown — local time in Utah is close enough for display; replace with exact timezone backend if needed.
const weddingDate = new Date("2027-06-12T11:00:00-06:00");
function updateCountdown() {
  const diff = weddingDate - new Date();
  if (diff <= 0) {
    document.getElementById("countdown").innerHTML = "<div><strong>♥</strong><span>06 · 12 · 27</span></div>";
    return;
  }
  const d = Math.floor(diff / 86400000);
  const h = Math.floor((diff / 3600000) % 24);
  const m = Math.floor((diff / 60000) % 60);
  const s = Math.floor((diff / 1000) % 60);
  document.getElementById("days").textContent = String(d).padStart(3,"0");
  document.getElementById("hours").textContent = String(h).padStart(2,"0");
  document.getElementById("minutes").textContent = String(m).padStart(2,"0");
  document.getElementById("seconds").textContent = String(s).padStart(2,"0");
}
updateCountdown();
setInterval(updateCountdown, 1000);

// Scroll reveal
const observer = new IntersectionObserver(entries => {
  entries.forEach(entry => {
    if (entry.isIntersecting) {
      entry.target.classList.add("visible");
      observer.unobserve(entry.target);
    }
  });
}, { threshold: .12 });
document.querySelectorAll(".reveal").forEach(el => observer.observe(el));

// RSVP demo: saves to browser localStorage.
const form = document.getElementById("rsvpForm");
const attendingFields = document.getElementById("attendingFields");
document.querySelectorAll('input[name="attendance"]').forEach(radio => {
  radio.addEventListener("change", () => {
    attendingFields.style.display = radio.value === "no" && radio.checked ? "none" : "block";
  });
});
form.addEventListener("submit", e => {
  e.preventDefault();
  const data = Object.fromEntries(new FormData(form).entries());
  data.events = [...form.querySelectorAll('input[name="events"]:checked')].map(x => x.value);
  data.savedAt = new Date().toISOString();
  const responses = JSON.parse(localStorage.getItem("gbWeddingRSVPs") || "[]");
  responses.push(data);
  localStorage.setItem("gbWeddingRSVPs", JSON.stringify(responses));
  form.style.display = "none";
  document.getElementById("successMessage").style.display = "block";
});

